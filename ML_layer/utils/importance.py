"""Permutation importance of the TFT's inputs, scored by the drop in test IC."""

import numpy as np
import pandas as pd

from ..framework.metrics import SIGNAL_HORIZONS, paired_ic_difference


def permute_feature(df: pd.DataFrame, feature: str, rng: np.random.Generator) -> tuple[pd.DataFrame, str]:
    """Break the link between ``feature`` and the target while keeping its distribution.

    Ticker-specific features are shuffled across tickers within each date, the
    standard test for a cross-sectional signal. Market-wide features (FRED,
    SPY, calendar) are identical across tickers on a date, so instead whole
    dates are permuted: every ticker gets the value from the same random date.
    """
    df = df.copy()
    by_date = df.groupby("time_idx")[feature]
    if by_date.nunique().gt(1).any():
        df[feature] = by_date.transform(lambda values: rng.permutation(values.to_numpy()))
        return df, "across tickers"
    per_date = by_date.first()
    shuffled = pd.Series(rng.permutation(per_date.to_numpy()), index=per_date.index)
    df[feature] = df["time_idx"].map(shuffled).astype(df[feature].dtype)
    return df, "across dates"


def permutation_importance(
    runner, dm, repeats: int = 1, seed: int = 0, features: list[str] | None = None,
) -> pd.DataFrame:
    """Drop in test IC when each model input is permuted, with Newey-West t-statistics.

    ΔIC = IC(original) − IC(permuted): positive means the model relies on the
    feature for its cross-sectional ranking; near zero means it adds nothing.
    t-statistics come from the paired daily IC differences, averaged over repeats.
    """
    rng = np.random.default_rng(seed)
    base_pred, target, dates, base_keys = runner.predict_dataset(dm, dm.build_test_dataset(dm.test_data))
    rows = []
    if features is None:
        # relative_time_idx (the decoder's only known input without calendar features) is generated by the
        # dataset, not a data column, and is the same for every sample, so there is nothing to shuffle.
        features = [f for f in dict.fromkeys(runner.ptf_model.encoder_variables + runner.ptf_model.decoder_variables)
                    if f in dm.test_data.columns]
    for i, feature in enumerate(features, 1):
        print(f"  [{i}/{len(features)}] permuting {feature}")
        diffs = []
        for _ in range(repeats):
            permuted, mode = permute_feature(dm.test_data, feature, rng)
            pred, perm_target, _, keys = runner.predict_dataset(dm, dm.build_test_dataset(permuted))
            if not (keys[["ticker", "time_idx"]].equals(base_keys[["ticker", "time_idx"]])
                    and np.allclose(perm_target, target)):
                raise RuntimeError(f"Permuting {feature} changed the test samples")
            diffs.append(paired_ic_difference(base_pred, pred, target, dates, SIGNAL_HORIZONS))
        rows.append({"feature": feature, "mode": mode, **pd.DataFrame(diffs).mean().to_dict()})
    return pd.DataFrame(rows).set_index("feature")
